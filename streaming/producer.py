"""
Kafka Producer

Publishes AI SaaS events generated by the simulator
to the Kafka ai-product-events topic.

Flow:
Simulator
    ↓
Kafka Producer
    ↓
ai-product-events
"""

# KafkaProducer comes from the external kafka-python package.
from kafka import KafkaProducer

from generators.simulator import simulate_user_journey

from streaming.kafka_config import (
    DEFAULT_TOPIC,
    producer_config,
)

from streaming.serializer import serialize_event


# ==========================================================
# Kafka Producer Factory
# ==========================================================

def create_producer() -> KafkaProducer:
    """
    Create and return a configured Kafka producer.
    """

    config = producer_config()

    producer = KafkaProducer(
        **config,
        value_serializer=serialize_event,
    )

    return producer


# ==========================================================
# Publish Events
# ==========================================================

def publish_events() -> None:
    """
    Generate one complete AI SaaS user journey
    and publish every event to Kafka.
    """

    print("=" * 80)
    print("Connecting to Kafka...")
    print("=" * 80)

    producer = create_producer()

    print("Kafka connection established.")
    print(f"Publishing to topic: {DEFAULT_TOPIC}")
    print("=" * 80)

    try:

        # simulate_user_journey() generates events one at a time.
        for event in simulate_user_journey():

            future = producer.send(
                DEFAULT_TOPIC,
                value=event,
            )

            # Wait until Kafka confirms the message.
            metadata = future.get(timeout=10)

            print(
                f"[SENT] "
                f"Event={event['event_type']} | "
                f"Partition={metadata.partition} | "
                f"Offset={metadata.offset}"
            )

    except KeyboardInterrupt:

        print("\nProducer stopped by user.")

    except Exception as error:

        print("\nKafka producer failed.")
        print(f"Error: {error}")

        raise

    finally:

        producer.flush()
        producer.close()

        print("=" * 80)
        print("Kafka Producer Closed")
        print("=" * 80)


# ==========================================================
# Main
# ==========================================================

if __name__ == "__main__":

    publish_events()